// Больше тысячи настоящих животных поверх основного древа (tree.js).
// Животные собраны в семьи. У семьи есть общий предок — отдельная ступень древа, от неё ветвятся виды.
//
// Строка вида:  "Название;размер;оттенок насыщенность яркость;особенности;факт"
//   размер и цвет можно не писать — тогда берутся от семьи;
//   особенности — через запятую: ключ=значение или просто ключ (значит 1). Ключ=0 убирает черту семьи.
//   Особые ключи: d= питание, h= среда, b= тип тела (как в tree.js).
//   Факт — короткое описание. Если его нет, описание собирается само.

const TRANSLIT = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "e", ж: "zh", з: "z", и: "i", й: "y", к: "k", л: "l", м: "m",
  н: "n", о: "o", п: "p", р: "r", с: "s", т: "t", у: "u", ф: "f", х: "h", ц: "c", ч: "ch", ш: "sh", щ: "sch",
  ъ: "", ы: "y", ь: "", э: "e", ю: "yu", я: "ya",
};
function slug(s) {
  return s.toLowerCase().split("").map(ch => TRANSLIT[ch] ?? (/[a-z0-9]/.test(ch) ? ch : "_")).join("").replace(/_+/g, "_").replace(/^_|_$/g, "");
}
const DIET_WORD = { photo: "Питается светом", filter: "Цедит мелкую еду", herb: "Травоядное", carn: "Хищник", omni: "Всеядное" };
const HAB_WORD = { micro: "в микромире", water: "в воде", land: "на суше" };

function parseTraits(s) {
  const f = {};
  if (!s) return f;
  for (const part of s.split(",")) {
    const [k, v] = part.split("=");
    const key = k.trim();
    if (!key) continue;
    if (v === undefined) f[key] = 1;
    else if (v.includes("/")) f[key] = v.split("/").map(Number);
    else f[key] = isNaN(+v) ? v.trim() : +v;
  }
  return f;
}

const USED_IDS = new Set(TREE.map(n => n.id));
// id — id предка семьи (или null — тогда виды крепятся прямо к parent).
function FAM(id, parent, name, base, desc, list) {
  let root = parent;
  if (id) { N(id, parent, name, base.b, base.h, base.d, base.sz, base.c, desc, { ...(base.f || {}) }); USED_IDS.add(id); root = id; }
  const famName = id ? name : (TREE.find(n => n.id === parent) || {}).name;
  for (const line of list) {
    const [nm, sz, col, tr, fact] = line.split(";").map(s => (s || "").trim());
    const t = parseTraits(tr);
    const body = t.b || base.b, hab = t.h || base.h, diet = t.d || base.d;
    delete t.b; delete t.h; delete t.d;
    let sid = "a_" + slug(nm), k = 2;
    while (USED_IDS.has(sid)) sid = "a_" + slug(nm) + "_" + k++;
    USED_IDS.add(sid);
    const c = col ? col.split(/\s+/).map(Number) : base.c;
    const text = fact || `${DIET_WORD[diet]}, живёт ${HAB_WORD[hab]}. Родня: ${famName}.`;
    N(sid, root, nm, body, hab, diet, sz ? +sz : base.sz, c, text, { ...(base.f || {}), ...t });
  }
}

